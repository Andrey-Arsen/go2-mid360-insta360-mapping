"""Задержки RTX-датчиков Isaac Sim 5.0 и время точек лидара — общие для записи стенда
(record_session.py) и перерисовки поездки робота (render_drive.py).

Всё замерено опытами при шаге 1/60: поза ставится перед шагом k, данные датчиков читаются после
него. Задержки зависят от того, ждёт ли Isaac конца рендера каждого кадра, поэтому режимов два.

Стенд (record_session.py), рендер асинхронный (как в Isaac по умолчанию): полный скан,
выданный после шага с временем T, начался в T − L кадров (L = LIDAR_LATENCY_FRAMES); кадр
камеры, прочитанный после шага k + C (C = CAMERA_LATENCY_FRAMES), показывает позу шага k.

Перерисовка поездки (render_drive.py), /app/hydraEngine/waitIdle = True (без него на тяжёлой
сцене данные доходят с плавающей задержкой): оба датчика отстают ровно на кадр. Скан, полученный
после шага k, несёт в info.transform позу лидара на свой конец — позу шага k − 1
(REPLAY_SCAN_END_LAG_FRAMES), а его точки лежат в SCAN_FRAMES кадрах перед ней (10 Гц при 60
кадрах/с). Кадр камеры, прочитанный после шага k + 1, показывает позу шага k
(REPLAY_CAMERA_LATENCY_FRAMES). Проверено на поездке Go2 по складу (робот без физики): облако
сходится с эталонным мешем лучше всего без сдвига времени (медиана 4.6 мм), все сканы начинаются
в k − 7; ноги робота на снимках точнее всего попадают в его маску при задержке камеры в 1 кадр.
"""

import numpy as np

DT = 1.0 / 60.0
SCAN_FRAMES = 6  # кадров рендера в полном скане Mid-360 (10 Гц)

# Стенд: асинхронный рендер.
LIDAR_LATENCY_FRAMES = 9
CAMERA_LATENCY_FRAMES = 4

# Перерисовка поездки: waitIdle.
REPLAY_SCAN_END_LAG_FRAMES = 1
REPLAY_CAMERA_LATENCY_FRAMES = 1


def point_times(scan_time, ts_ns, latency_frames=LIDAR_LATENCY_FRAMES):
    """Абсолютное время точек полного скана из смещений внутри кадров рендера: скан начался в
    scan_time − latency_frames кадров.

    Счётчик времени ScanBuffer сбрасывается в каждом кадре; первые точки скана могут быть
    хвостом кадра из предыдущего скана."""
    frame = np.r_[0, np.cumsum(np.diff(ts_ns) < 0)]
    if ts_ns[0] > 15_000_000:
        frame = frame - 1
    return scan_time - latency_frames * DT + frame * DT + ts_ns * 1e-9
